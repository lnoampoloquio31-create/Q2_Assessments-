# Activity 3
# MLBB Rank Analyzer

ranks = ["Legend", "Epic", "Mythic", "Mythical Honor", "Mythical Glory"]


# Function to display ranks
def display_ranks():
    print("\nMLBB Player Ranks:")
    for i in range(len(ranks)):
        print(f"Player {i + 1}: {ranks[i]}")


# Function to search for a rank
def search_rank():
    target = input("Enter the rank to search: ").strip().title()

    if target in ranks:
        print("Rank found!")
    else:
        print("Rank not found.")


# Function to count total players
def compute_average():
    total = len(ranks)
    print(f"Total Players: {total}")


# Function to update a rank
def update_rank():
    display_ranks()

    index = int(input("\nEnter player number to update: "))

    if 1 <= index <= len(ranks):
        new_rank = input("Enter the new rank: ").strip().title()

        ranks[index - 1] = new_rank

        print("Rank successfully updated!")
    else:
        print("Invalid player number.")


